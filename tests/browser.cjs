const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs/promises');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.resolve(process.env.SITE_QA_OUTPUT || path.join(root, '../lexical_access_site_preview'));
const publicFiles = new Set(['index.html', 'styles.css', 'app.js', 'mock-data.js', 'assets/favicon.svg']);
const mime = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.svg': 'image/svg+xml' };
const checks = [], errors = [], requests = [];
const check = (name, value) => { assert.ok(value, name); checks.push(name); };
const server = http.createServer(async (req, res) => {
  const filename = new URL(req.url, 'http://localhost').pathname.replace(/^\/project\//, '') || 'index.html';
  if (!publicFiles.has(filename)) { res.writeHead(404).end(); return; }
  try { res.setHeader('Content-Type', mime[path.extname(filename)]); res.end(await fs.readFile(path.join(root, filename))); }
  catch { res.writeHead(500).end(); }
});
let browser;
(async () => {
  await fs.mkdir(path.join(output, 'figs'), { recursive: true });
  await fs.mkdir(path.join(output, 'meta'), { recursive: true });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}/project/`;
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) errors.push(`HTTP ${response.status()} ${response.url()}`); });
  page.on('request', request => requests.push(request.url()));
  await page.goto(base);
  await page.waitForSelector('#brain-stage svg');
  check('Three task maps render under GitHub project subpath', await page.locator('#brain-stage svg').count() === 3);
  check('No autoplay with reduced motion', await page.locator('#play').getAttribute('aria-label') === 'Play animation');
  await page.screenshot({ path: path.join(output, 'figs/mobile-story.png'), fullPage: false });
  for (const width of [320, 375, 390, 430, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    check(`No horizontal overflow at ${width}px`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.locator('#toggle-chapters').click();
    check(`Expanded story fits at ${width}px`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.locator('#toggle-chapters').click();
    check(`All chapters collapse at ${width}px`, await page.locator('.chapter[open]').count() === 0);
    await page.locator('a.nav-explore').click();
    await page.waitForFunction(() => document.querySelector('#hga').open);
    check(`HGA link reopens chapter at ${width}px`, await page.locator('#hga').getAttribute('open') !== null);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base);
  await page.goto(base + '#hga');
  await page.waitForFunction(() => document.querySelector('#explorer').getBoundingClientRect().top <= 100);
  check('Direct HGA URL positions explorer', await page.locator('#explorer').evaluate(el => el.getBoundingClientRect().top >= 0));
  check('Mobile task maps stack', await page.locator('.brain-panel').evaluateAll(els => els[1].getBoundingClientRect().top > els[0].getBoundingClientRect().top));
  await page.screenshot({ path: path.join(output, 'figs/mobile-hga-tasks.png'), fullPage: false });
  const before = await page.locator('#brain-stage').innerHTML();
  await page.locator('#time').fill('470');
  await page.locator('#time').dispatchEvent('input');
  check('Timeline updates maps', await page.locator('#brain-stage').innerHTML() !== before);
  check('Time output updates', (await page.locator('#time-output').textContent()).includes('470'));
  await page.locator('#time').focus();
  await page.keyboard.press('ArrowRight');
  check('Keyboard timeline adjustment', await page.locator('#time').inputValue() === '480');
  await page.getByRole('button', { name: 'HGA contrast', exact: true }).click();
  check('Contrast legend shows both signs', (await page.locator('#signal-key').textContent()).includes('Word > Nonword'));
  await page.locator('[data-view="contours"]').click();
  check('Overlay replaces three maps', await page.locator('#brain-stage svg').count() === 1);
  check('Intersection masks exist', await page.locator('#brain-stage mask').count() === 6);
  await page.locator('#shared-scope').selectOption('active');
  check('Active-only overlap uses two tasks per sign', await page.locator('#brain-stage mask').count() === 4);
  await page.locator('#shared-scope').selectOption('none');
  check('Contours-only removes overlap masks', await page.locator('#brain-stage mask').count() === 0);
  await page.locator('#shared-scope').selectOption('all');
  await page.locator('#alignment').selectOption('offset');
  check('Changing alignment preserves mock frame', await page.locator('#time').inputValue() === '-120');
  await page.locator('#reset').click();
  check('Offset reset reaches zero', await page.locator('#time').inputValue() === '0');
  await page.locator('#play').click();
  await page.waitForTimeout(300);
  check('Explicit play advances time', Number(await page.locator('#time').inputValue()) > 0);
  await page.locator('#play').click();
  const paused = await page.locator('#time').inputValue();
  await page.waitForTimeout(150);
  check('Pause holds time', await page.locator('#time').inputValue() === paused);
  await page.locator('#play').click();
  await page.locator('#hga > summary').click();
  await page.waitForTimeout(80);
  check('Collapsing HGA pauses', await page.locator('#play').getAttribute('aria-label') === 'Play animation');
  const saved = '#hga?metric=contrast&view=contours&scope=active&align=offset&roi=frontal&t=850';
  await page.goto(base + saved);
  await page.waitForFunction(() => document.querySelector('#hga').open);
  check('Saved view restores metric', await page.locator('[data-metric="contrast"]').getAttribute('aria-pressed') === 'true');
  check('Saved view restores region', await page.locator('[data-roi="frontal"]').getAttribute('aria-pressed') === 'true');
  check('Saved view restores time and alignment', await page.locator('#time').inputValue() === '250');
  await page.screenshot({ path: path.join(output, 'figs/mobile-hga-contours.png'), fullPage: false });
  // Force clipboard fallback so this path is deterministic on any browser host.
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined }));
  await page.locator('#copy-hga').click();
  check('Clipboard failure opens copy dialog', await page.locator('#share-dialog').evaluate(el => el.open));
  const copied = new URL(await page.locator('#share-url').inputValue());
  check('Saved view link retains subpath', copied.origin + copied.pathname === base);
  const copiedParams = new URLSearchParams(copied.hash.split('?')[1]);
  check('Saved view link retains settings', [...new URLSearchParams(saved.split('?')[1])].every(([key, value]) => copiedParams.get(key) === value));
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.locator('#references').evaluate(el => { el.open = true; });
  await page.locator('#copy-story').click();
  check('Story link goes to root', await page.locator('#share-url').inputValue() === base);
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.locator('#copy-session').click();
  check('Poster card goes directly to HGA', await page.locator('#share-url').inputValue() === base + '#hga');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.goto(base + '#hga?metric=bad&view=unknown&t=999999');
  check('Untrusted URL values fall back and clamp', await page.locator('[data-metric="activation"]').getAttribute('aria-pressed') === 'true' && await page.locator('#time').inputValue() === '1200');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base);
  await page.screenshot({ path: path.join(output, 'figs/desktop-story.png'), fullPage: false });
  await page.goto(base + '#hga?metric=contrast&view=contours&scope=all&t=460');
  await page.waitForFunction(() => document.querySelector('#explorer').getBoundingClientRect().top <= 100);
  await page.screenshot({ path: path.join(output, 'figs/desktop-hga.png'), fullPage: false });
  const noJsContext = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
  const noJs = await noJsContext.newPage();
  await noJs.goto(base);
  await noJs.locator('#components > summary').click();
  check('Poster narrative works without JavaScript', await noJs.locator('#components').getAttribute('open') !== null && (await noJs.locator('#components').textContent()).includes('Superior temporal'));
  await noJsContext.close();
  check('No runtime or asset errors', errors.length === 0);
  check('Page uses no external data or runtime assets', requests.every(url => url.startsWith(base)));
  const report = { status: 'passed', date: '2026-11-11', browser: 'Chromium', checks, errors, notes: ['Desktop Chromium with viewport emulation; physical iOS/Android not tested.', 'All maps and timings are synthetic.', 'Preview screenshots are outside the source repository.'] };
  await fs.writeFile(path.join(output, 'meta/browser-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ status: report.status, checks: checks.length, output }, null, 2));
})().catch(async error => {
  console.error(error.stack);
  await fs.mkdir(path.join(output, 'meta'), { recursive: true });
  await fs.writeFile(path.join(output, 'meta/browser-failure.json'), JSON.stringify({ error: error.message, checks, errors }, null, 2));
  process.exitCode = 1;
}).finally(async () => { if (browser) await browser.close(); server.close(); });
