const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const http=require('node:http');
const output=path.resolve(process.env.SITE_SURFACE_OUTPUT||path.join(__dirname,'../../lexical_access_site_preview/surface-v2'));
const checks=[],errors=[];
const check=(name,value)=>{assert.ok(value,name);checks.push(name)};
let browser,server;
(async()=>{
  let base=process.env.SITE_SURFACE_URL;
  if(!base){
    const root=path.join(output,'meta/public-site');
    server=http.createServer(async(req,res)=>{
      let rel=new URL(req.url,'http://localhost').pathname.replace(/^\/lexical-access\//,'');
      if(!rel||rel.endsWith('/'))rel+='index.html';
      if(!['index.html','real-data.js','surface-view.js','real-app.js','styles.css','site-config.js','version.json','hga/index.html','assets/favicon.svg','assets/cogan-lab.png','assets/duke-bme.png'].includes(rel)){res.writeHead(404).end();return;}
      try{res.setHeader('Content-Type',rel.endsWith('.js')?'text/javascript':rel.endsWith('.css')?'text/css':rel.endsWith('.json')?'application/json':rel.endsWith('.png')?'image/png':rel.endsWith('.svg')?'image/svg+xml':'text/html');res.end(await fs.readFile(path.join(root,rel)));}catch{res.writeHead(500).end();}
    });
    await new Promise(r=>server.listen(0,'127.0.0.1',r));base=`http://127.0.0.1:${server.address().port}/lexical-access/`;
  }
  browser=await chromium.launch({args:['--enable-unsafe-swiftshader']});
  const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,reducedMotion:'reduce'});
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)errors.push(r.url());});
  await page.goto(base+'#hga');await page.waitForSelector('#brain-stage canvas[data-camera]');
  const settle=async()=>{await page.waitForFunction(()=>{const y=document.querySelector('#explorer').getBoundingClientRect().top;return y>=0&&y<=100;});await page.waitForTimeout(150);};
  await settle();
  const canvases=page.locator('#brain-stage canvas');
  const cameras=()=>canvases.evaluateAll(cs=>cs.map(c=>c.dataset.camera));
  const pixels=()=>canvases.evaluateAll(cs=>cs.map(c=>c.toDataURL()));
  const synchronized=async()=>{const v=await cameras();return v.length===3&&v.every(x=>x===v[0]);};
  check('All three meshes have over 20,000 faces',await canvases.evaluateAll(cs=>cs.length===3&&cs.every(c=>Number(c.dataset.faces)>20000)));
  const initial=await pixels();
  const box=await canvases.first().boundingBox(),x=box.x+box.width/2,y=box.y+box.height/2;
  await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x+45,y+18,{steps:8});await page.mouse.up();await page.waitForTimeout(60);
  check('Mouse drag rotates all three cameras together',await synchronized()&&(await cameras())[0]!=='0:0');
  const rotated=await pixels();check('Every task image rotates',rotated.every((p,i)=>p!==initial[i]));
  let angle=(await cameras())[0];await page.locator('#time').fill('12');await page.locator('#time').dispatchEvent('input');
  check('Scrubbing time preserves the shared angle',await synchronized()&&(await cameras())[0]===angle);
  await page.locator('[data-view=contours]').click();check('Contours preserve the task camera',(await cameras())[0]===angle);
  await page.locator('[data-view=tasks]').click();check('Returning to three tasks keeps synchronization',await synchronized()&&(await cameras())[0]===angle);
  await page.locator('[data-metric=contrast]').click();check('Changing metric preserves rotation',await synchronized()&&(await cameras())[0]===angle);
  await page.locator('#map-settings > summary').click();
  await page.locator('[data-hemi=rh]').click();check('RH retains the shared camera',await synchronized()&&(await cameras())[0]===angle);
  await page.locator('[data-hemi=lh]').click();await page.locator('[data-metric=activation]').click();
  await page.locator('#map-settings > summary').click();
  await page.locator('#reset-view').click();await page.waitForTimeout(60);check('Reset view restores all three lateral cameras',await synchronized()&&(await cameras())[0]==='0:0');
  await canvases.nth(1).focus();await page.keyboard.press('ArrowRight');await page.waitForTimeout(60);
  check('Keyboard rotation on task two synchronizes all tasks',await synchronized()&&(await cameras())[0]==='5:0');
  await page.keyboard.press('Home');await page.waitForTimeout(60);check('Home restores lateral view',(await cameras())[0]==='0:0');
  const cdp=await context.newCDPSession(page),touchBox=await canvases.first().boundingBox();
  const tx=touchBox.x+touchBox.width*.5,ty=touchBox.y+touchBox.height*.5,scrollBefore=await page.evaluate(()=>scrollY);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:tx,y:ty}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:tx+32,y:ty+22}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await page.waitForTimeout(100);
  check('Real touch gesture rotates synchronized maps',await synchronized()&&(await cameras())[0]!=='0:0');
  check('Dragging a brain does not scroll the document',Math.abs((await page.evaluate(()=>scrollY))-scrollBefore)<2);
  check('Pinch zoom remains available',await canvases.first().evaluate(c=>getComputedStyle(c).touchAction.includes('pinch-zoom')));
  angle=(await cameras())[0];await page.mouse.move(tx+10,ty+10);await page.waitForTimeout(40);
  check('Pointer release stops rotation',(await cameras())[0]===angle);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:tx,y:ty}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
  check('Canceled touch clears dragging state',await page.locator('canvas.is-dragging').count()===0);
  const marginStart=await page.evaluate(()=>scrollY);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:5,y:650}]});
  for(const y of [620,590,550,510])await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:5,y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await page.waitForTimeout(250);
  check('Page margin still scrolls with a finger',(await page.evaluate(()=>scrollY))>marginStart+20);

  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{value:undefined,configurable:true}));
  await page.locator('#copy-hga').click();const url=new URL(await page.locator('#share-url').inputValue());const params=new URLSearchParams(url.hash.split('?')[1]);
  check('Saved view includes camera yaw and pitch',params.has('yaw')&&params.has('pitch')&&Number(params.get('yaw'))!==0);
  await page.getByRole('button',{name:'Done',exact:true}).click();
  await page.goto(base+'#hga?yaw=125&pitch=55&metric=contrast&view=tasks');await page.waitForFunction(()=>document.querySelector('#brain-stage canvas').dataset.camera==='125:55');
  await settle();
  check('Saved rotation restores all panels',await synchronized());
  check('Rotated surfaces fit inside the viewport',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const prefix=process.env.SITE_SURFACE_URL?'published-':'';
  await page.screenshot({path:path.join(output,'figs',prefix+'mobile-rotated.png')});
  await page.locator('#reset-view').click();await page.locator('[data-metric=activation]').click();await page.waitForTimeout(60);
  await page.screenshot({path:path.join(output,'figs',prefix+'mobile-surface.png')});
  await page.setViewportSize({width:1440,height:1050});await page.goto(base+'#hga?view=contours&metric=contrast&direction=wdnw&yaw=35&pitch=-20&t=700');await page.waitForFunction(()=>document.querySelector('#brain-stage canvas').dataset.camera==='35:-20');
  await settle();
  await page.screenshot({path:path.join(output,'figs',prefix+'desktop-rotated-contours.png')});
  const timing=await page.evaluate(()=>{
    const bundle=window.LexicalRealBundle,cell=bundle.cells['activation-onset'],views=['passive','decision','repeat'].map(task=>({task,view:new window.LexicalSurfaceView(document.createElement('canvas'),bundle,'lh')}));
    for(const item of views)item.view.draw(cell,8,{task:item.task});
    const start=performance.now();for(let i=0;i<30;i++)for(const item of views)item.view.draw(cell,8,{task:item.task,camera:{yaw:i*2,pitch:10}});
    const ms=(performance.now()-start)/30;for(const item of views)item.view.destroy();return ms;
  });
  const fallback=await context.newPage();fallback.on('pageerror',e=>errors.push(e.message));
  await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type==='webgl'?null:original.call(this,type,...args)};});
  await fallback.goto(base+'#hga');await fallback.waitForSelector('#brain-stage canvas[data-camera]');
  await fallback.locator('#brain-stage canvas').first().focus();await fallback.keyboard.press('ArrowRight');
  await fallback.waitForFunction(()=>[...document.querySelectorAll('#brain-stage canvas')].every(c=>c.dataset.camera==='5:0'));
  check('Canvas2D fallback also synchronizes rotation',await fallback.locator('#brain-stage canvas').evaluateAll(cs=>cs.length===3&&cs.every(c=>c.dataset.renderer==='canvas2d')));
  await fallback.close();
  check('No runtime or asset errors',errors.length===0);
  const report={status:'passed',url:base,checks,errors,mean_cpu_submission_ms_per_three_panel_rotation:timing,notes:['Actual CDP touch gestures plus mouse and keyboard; Chromium software GPU.','Physical mobile performance is not inferred from CPU submission timing.']};
  await fs.writeFile(path.join(output,'meta',prefix+'surface-browser.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify({status:'passed',checks:checks.length,rotation_cpu_ms:timing}));
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();if(server)server.close();});
